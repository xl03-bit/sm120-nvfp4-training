"""SM120 full NVFP4 training: fused quantization, no full-weight pad copies.

This is an opt-in experimental backend, NOT a driver or a global torch patch.
Keeps FP32 master parameters and the optimizer unchanged. All converted Linear
layers use native FP4 GEMMs in fprop, dgrad and wgrad. SR and H16 RHT remain on.
CUDA Graph capture / torch.compile / distributed wrappers are not supported by
this revision. It intentionally never switches a converted layer to BF16 GEMM.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Optional
import os
import hashlib
import json
import torch
from torch import nn

_EXT = None
_SIGNS: dict[torch.device, torch.Tensor] = {}
_BACKWARD_MODES: Optional[dict[str, str]] = None
_BACKWARD_CHOICES = ("fast_pair", "fast_reuse", "fast_fresh")
CONFIG_FILENAME = "verified_backend.json"
_SEED = 0
_STATS = {"fp4_gemm": 0, "quant": 0, "sr_quant": 0, "rht_quant": 0,
          "reused_weight_amax": 0, "packed_activation_saved": 0,
          "legacy_fp4_quant_odd_transpose": 0,
          "reference_dgrad": 0, "reference_wgrad": 0,
          "fresh_dgrad_scale": 0, "reference_fprop": 0}


def extension():
    global _EXT
    if _EXT is None:
        if not torch.cuda.is_available():
            raise RuntimeError("NVFP4 v3 requires a CUDA GPU; no CPU/BF16 fallback")
        if torch.cuda.get_device_capability() != (12, 0):
            raise RuntimeError("This CUDA extension targets SM120 only")
        from torch.utils.cpp_extension import load
        here = Path(__file__).resolve().parent / "csrc"
        _EXT = load(
            name="sm120_training_base",
            sources=[str(here / "bindings.cpp"), str(here / "kernels.cu")],
            extra_cflags=["-O3"],
            extra_cuda_cflags=["-O3", "--fmad=false", "-gencode",
                               "arch=compute_120a,code=sm_120a"],
            verbose=os.environ.get("NVFP4_BUILD_VERBOSE", "0") == "1",
        )
    return _EXT


def _backend_fingerprint() -> dict:
    root = Path(__file__).resolve().parent
    files = sorted([*root.glob("*.py"), *root.glob("csrc*/*.cu"), *root.glob("csrc*/*.cpp"),
                    *(root.parent / "_verification").glob("*.py")])
    digest = hashlib.sha256()
    for item in files:
        digest.update(item.relative_to(root.parent).as_posix().encode("utf-8"))
        digest.update(item.read_bytes())
    import triton
    import importlib.metadata
    return {
        "schema": 3, "triton": triton.__version__, "torchao": importlib.metadata.version("torchao"), "source_sha256": digest.hexdigest(),
        "torch": torch.__version__, "cuda_runtime": torch.version.cuda,
        "gpu_capability": list(torch.cuda.get_device_capability()),
        "gpu_name": torch.cuda.get_device_name(),
    }


def verification_file():
    fingerprint = json.dumps(_backend_fingerprint(), sort_keys=True).encode()
    key = hashlib.sha256(fingerprint).hexdigest()
    cache = Path(os.environ.get("XDG_CACHE_HOME", Path.home()/".cache"))
    return cache/"sm120-nvfp4-training"/key/CONFIG_FILENAME


def set_backward_modes(*, aligned: str, irregular: str) -> None:
    """For the verifier to select a mode, before construction of any models."""
    global _BACKWARD_MODES
    if aligned not in _BACKWARD_CHOICES or irregular not in _BACKWARD_CHOICES:
        raise ValueError(f"Unknown NVFP4 backward mode: {aligned}, {irregular}")
    _BACKWARD_MODES = {"aligned": aligned, "irregular": irregular}


def write_verified_modes(*, aligned: str, irregular: str) -> Path:
    """Persist modes ONLY after the GPU verification suite has passed."""
    set_backward_modes(aligned=aligned, irregular=irregular)
    payload = dict(_backend_fingerprint(), modes=dict(_BACKWARD_MODES),
                   proof="GPU parity + optimizer smoke tests required; generated by verify_fast_v2.py")
    path = verification_file()
    path.parent.mkdir(exist_ok=True, parents=True)
    import tempfile
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        tmp = Path(f.name)
    tmp.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    tmp.replace(path)
    return path


def ensure_verified_modes() -> dict[str, str]:
    """Refuse unverified compiled backend rather than silently changing precision."""
    global _BACKWARD_MODES
    if _BACKWARD_MODES is not None:
        return dict(_BACKWARD_MODES)
    path = verification_file()
    if not path.is_file():
        raise RuntimeError("This NVFP4 v3 backend has not been GPU-verified. "
                           "Run python -m nvfp4_training verify before using it in training.")
    payload = json.loads(path.read_text(encoding="utf-8"))
    current = _backend_fingerprint()
    mismatch = {k: (payload.get(k), v) for k, v in current.items()
                if payload.get(k) != v}
    if mismatch:
        raise RuntimeError(f"Stale or different-device NVFP4 verification: {mismatch}. "
                           "Run python -m nvfp4_training verify again to reverify.")
    modes = payload.get("modes", {})
    set_backward_modes(aligned=modes.get("aligned", ""),
                       irregular=modes.get("irregular", ""))
    print(f"[NVFP4 v3] verified backward modes: {_BACKWARD_MODES}; SR/RHT enabled", flush=True)
    return dict(_BACKWARD_MODES)


def current_backward_modes() -> dict[str, str]:
    return ensure_verified_modes()


def reset_stats(seed: int = 0) -> None:
    global _SEED
    _SEED = int(seed)
    for key in _STATS:
        _STATS[key] = 0


def stats() -> dict[str, int]:
    return dict(_STATS)


def round128(n: int) -> int:
    if n <= 0:
        raise ValueError("Empty dimensions are not supported")
    return (n + 127) // 128 * 128


def get_signs(device: torch.device) -> torch.Tensor:
    device = torch.device(device)
    if device not in _SIGNS:
        gen = torch.Generator(device="cpu").manual_seed(1)
        _SIGNS[device] = (torch.randint(0, 2, (16,), generator=gen).float() * 2 - 1).to(device)
    return _SIGNS[device]


@dataclass
class Packed:
    data: torch.Tensor
    scale: torch.Tensor
    pts: torch.Tensor
    dtype: torch.dtype

    @property
    def shape(self):
        return (self.data.shape[0], self.data.shape[1] * 2)


def quantize(x: torch.Tensor, *, sr: bool = False, rht: bool = False,
             signs: Optional[torch.Tensor] = None, seed: Optional[int] = None,
             pts: Optional[torch.Tensor] = None) -> Packed:
    """Read original strides directly and virtually zero-pad to 128.

    'pts' is only reused for the same unchanged weight's transposed view within
    one forward/backward pair. No cross-optimizer-step weight cache is kept.
    """
    global _SEED
    if x.ndim != 2 or x.device.type != "cuda":
        raise ValueError("quantize expects a 2D CUDA tensor")
    if x.dtype not in (torch.float32, torch.bfloat16):
        raise TypeError(f"Unsupported dtype {x.dtype}; use BF16 autocast / FP32 masters")
    if any(s == 0 for s in x.stride()):
        # Expanded views need one materialization, never silently misindex them.
        x = x.contiguous()
    if signs is None:
        signs = get_signs(x.device)
    if seed is None:
        seed = _SEED
        if sr:
            _SEED = (_SEED + 1) & 0xffffffff
    d, s, p = extension().quantize(x, signs,
                                  round128(x.shape[0]), round128(x.shape[1]),
                                  sr, rht, int(seed), pts, False)
    _STATS["quant"] += 1
    _STATS["sr_quant"] += int(sr)
    _STATS["rht_quant"] += int(rht)
    _STATS["reused_weight_amax"] += int(pts is not None)
    return Packed(d, s, p, x.dtype)


def matmul_packed(a: Packed, bt: Packed, *, rows: Optional[int] = None,
                  cols: Optional[int] = None, output_dtype: Optional[torch.dtype] = None,
                  bias: Optional[torch.Tensor] = None) -> torch.Tensor:
    """a @ bt.T, strictly native FP4 tensor-core _scaled_mm, FP32 accumulation."""
    if a.shape[1] != bt.shape[1]:
        raise ValueError("Packed contraction dimensions do not match")
    rows = a.shape[0] if rows is None else rows
    cols = bt.shape[0] if cols is None else cols
    output_dtype = a.dtype if output_dtype is None else output_dtype
    if output_dtype not in (torch.float32, torch.bfloat16):
        raise TypeError("Output must be FP32 or BF16")
    raw = torch._scaled_mm(
        a.data.view(torch.float4_e2m1fn_x2),
        bt.data.t().view(torch.float4_e2m1fn_x2),
        a.scale.view(torch.float8_e4m3fn),
        bt.scale.view(torch.float8_e4m3fn),
        out_dtype=a.dtype,
        use_fast_accum=False,
    )
    _STATS["fp4_gemm"] += 1
    return extension().rescale(raw, a.pts, bt.pts, rows, cols,
                               output_dtype == torch.float32, bias)


class _LinearFn(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, w, bias, signs, need_x, need_w, need_bias, save_packed):
        modes = ensure_verified_modes()
        original_shape = tuple(x.shape)
        x2 = x.reshape(-1, x.shape[-1])
        m, k = x2.shape
        n = w.shape[0]
        is_aligned = all(d % 128 == 0 for d in (m, k, n))
        mode = modes["aligned" if is_aligned else "irregular"]
        a = quantize(x2, signs=signs)
        if mode == "fast_pair" and need_x and w.is_contiguous():
            data, scale, pts, td, ts = extension().quantize(
                w, signs, round128(n), round128(k), False, False, 0, None, True)
            b = Packed(data, scale, pts, w.dtype)
            _STATS["quant"] += 2
            _STATS["reused_weight_amax"] += 1
        else:
            b = quantize(w, signs=signs)
        y = matmul_packed(a, b, rows=m, cols=n, output_dtype=x.dtype, bias=bias)
        wpts = b.pts
        # save_for_backward retains parameter version tracking for backward.
        tensors = [w, wpts, signs]
        if need_w:
            if save_packed:
                # Encode the EXACT orientation / RHT needed by wgrad now, then
                # discard the high-precision saved activation for this layer.
                xp = quantize(x2.t(), rht=True, signs=signs)
                tensors += [xp.data, xp.scale, xp.pts]
                _STATS["packed_activation_saved"] += 1
            else:
                tensors += [x2]
        ctx.paired = mode == "fast_pair" and need_x and w.is_contiguous()
        if ctx.paired:
            tensors.extend((td, ts))
        ctx.save_for_backward(*tensors)
        ctx.original_shape = original_shape
        ctx.xdtype = x.dtype
        ctx.bias_dtype = bias.dtype if bias is not None else None
        ctx.need_x, ctx.need_w, ctx.need_bias = need_x, need_w, need_bias
        ctx.save_packed = save_packed
        ctx.mode = mode
        ctx.m, ctx.k, ctx.n = m, k, n
        return y.reshape(*original_shape[:-1], n)

    @staticmethod
    @torch.autograd.function.once_differentiable
    def backward(ctx, grad):
        saved = ctx.saved_tensors
        w, wpts, signs = saved[:3]
        g = grad.reshape(ctx.m, ctx.n)
        dx = dw = db = None
        if ctx.need_x:
            aq = quantize(g, sr=True, signs=signs)
            if ctx.paired:
                wq = Packed(saved[-2], saved[-1], wpts, w.dtype)
            elif ctx.mode in ("fast_pair", "fast_reuse"):
                wq = quantize(w.t(), signs=signs, pts=wpts)
            else:
                wq = quantize(w.t(), signs=signs)
                _STATS["fresh_dgrad_scale"] += 1
            dx = matmul_packed(aq, wq, rows=ctx.m, cols=ctx.k,
                               output_dtype=ctx.xdtype)
            dx = dx.reshape(ctx.original_shape).to(ctx.xdtype)
        if ctx.need_w:
            aq = quantize(g.t(), sr=True, rht=True, signs=signs)
            if ctx.save_packed:
                xq = Packed(saved[3], saved[4], saved[5], ctx.xdtype)
            else:
                xq = quantize(saved[3].t(), rht=True, signs=signs)
            dw = matmul_packed(aq, xq, rows=ctx.n, cols=ctx.k,
                               output_dtype=w.dtype)
        if ctx.need_bias:
            # Match the usual autograd bias sum: reduce BF16 gradient in FP32,
            # then cast through the forward output's dtype before master dtype.
            db = g.sum(0).to(ctx.bias_dtype)
        return dx, dw, db, None, None, None, None, None


class NVFP4LinearV3(nn.Linear):
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if x.device.type != "cuda":
            raise RuntimeError("NVFP4 v3 requires CUDA; refusing CPU fallback")
        if x.shape[-1] != self.in_features:
            raise ValueError(f"Input last dimension {x.shape[-1]} != {self.in_features}")
        if self.weight.dtype != torch.float32:
            raise TypeError("Keep FP32 master weights; use autocast, not model.bfloat16()")
        grad_enabled = torch.is_grad_enabled()
        return _LinearFn.apply(x, self.weight, self.bias, self._nvfp4_signs,
                               grad_enabled and x.requires_grad,
                               grad_enabled and self.weight.requires_grad,
                               grad_enabled and self.bias is not None and self.bias.requires_grad,
                               self._nvfp4_save_packed)


def enable_nvfp4(model: nn.Module, *, save_quantized_activations: bool = True) -> nn.Module:
    """Convert ordinary nn.Linear, preserving the EXACT Parameter objects.

    Call once before the optimizer, on a CUDA FP32 model. No system package is
    changed. Parameter/state_dict names are preserved; signs are nonpersistent.
    Shared modules and shared Parameter references remain shared. Higher-order
    gradients, FSDP/DTensor/torch.compile/CUDA Graphs need separate integration.
    """
    ensure_verified_modes()
    seen: set[int] = set()
    def convert(m: nn.Module):
        if id(m) in seen:
            return
        seen.add(id(m))
        if isinstance(m, NVFP4LinearV3):
            m._nvfp4_save_packed = bool(save_quantized_activations)
            return
        if isinstance(m, nn.Linear):
            if type(m) is not nn.Linear:
                raise TypeError(f"Refusing to override custom Linear subclass: {type(m)}")
            if m.weight.device.type != "cuda" or m.weight.dtype != torch.float32:
                raise TypeError("Move model to CUDA with FP32 master weights before conversion")
            # No reinitialization, weight copying or extra full-size Parameter.
            m.__class__ = NVFP4LinearV3
            m.register_buffer("_nvfp4_signs", get_signs(m.weight.device), persistent=False)
            m._nvfp4_save_packed = bool(save_quantized_activations)
            return
        for child in m._modules.values():
            if child is not None:
                convert(child)
    convert(model)
    return model
